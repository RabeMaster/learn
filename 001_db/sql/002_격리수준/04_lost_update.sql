-- 4. Lost Update - 내 갱신이 남의 갱신에 묻혀 사라지는 것
--
-- 짱구 계좌(잔액 10만) 하나에 출금 요청이 두 건 동시에 들어옵니다.
--   세션 1: ATM에서 7만 원 출금
--   세션 2: 휴대폰 앱에서 5만 원 출금
-- 12만 원이 빠져나갔는데 잔액은 5만 원이 됩니다. 7만 원이 증발합니다.
--
-- PostgreSQL 16 기본값인 READ COMMITTED에서 재현됩니다.
-- ============================================================
-- 세션 두 개를 띄우고 [S1], [S2] 옆의 번호 순서대로 한 블록씩 실행합니다.
-- ------------------------------------------------------------


-- [S1] 1  (ATM, 7만 원 출금)
BEGIN;
SELECT balance FROM accounts WHERE id = 1;
-- 100000


-- [S2] 2  (휴대폰 앱, 5만 원 출금)
BEGIN;
SELECT balance FROM accounts WHERE id = 1;
-- 100000  <- 둘 다 같은 값을 읽었습니다


-- [S1] 3
-- 애플리케이션에서 계산: 100000 - 70000 = 30000
UPDATE accounts SET balance = 30000 WHERE id = 1;


-- [S2] 4
-- 애플리케이션에서 계산: 100000 - 50000 = 50000
UPDATE accounts SET balance = 50000 WHERE id = 1;
-- 여기서 커서가 멈추고 대기합니다. 세션 1이 잡은 행 잠금이 풀릴 때까지 기다립니다.


-- [S1] 5
COMMIT;
-- 이 순간 세션 2의 대기가 풀립니다.


-- [S2] 6
COMMIT;


-- [S1] 7  (아무 세션에서나)
SELECT * FROM accounts WHERE id = 1;
-- balance = 50000
-- 7만 원 출금이 통째로 사라졌습니다.


