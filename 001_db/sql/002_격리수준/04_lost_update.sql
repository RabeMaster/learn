--   문제는 기다린 다음입니다. 세션 2가 들고 있던 50000은
--   "옛날 잔액 10만"을 보고 계산한 값인데, 그걸 그대로 덮어썼습니다.
--   DB는 순서는 지켜줬지만, 계산의 근거가 낡았다는 건 모릅니다.
