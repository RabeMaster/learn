-- 그래서 동시 출금은 어떻게 막나
--
-- Lost Update의 진짜 원인은 격리 수준이 아니라
-- "SELECT로 읽고 -> 애플리케이션에서 계산하고 -> UPDATE로 덮어쓰는" 패턴 자체입니다.
-- 계산을 DB한테 맡겨서 한 문장으로 쓰면, 제일 낮은 기본 격리 수준에서도 안 틀립니다.
--
-- 시작 전에 00_reset.sql 로 되돌립니다.
-- ============================================================
-- 세션 두 개를 띄우고 [S1], [S2] 옆의 번호 순서대로 한 블록씩 실행합니다.
-- 격리 수준은 건드리지 않습니다. PostgreSQL 16 기본값 READ COMMITTED 그대로입니다.
-- ------------------------------------------------------------


-- [S1] 1  (ATM, 7만 원 출금)
BEGIN;
UPDATE accounts SET balance = balance - 70000 WHERE id = 1;


-- [S2] 2  (휴대폰 앱, 5만 원 출금)
BEGIN;
UPDATE accounts SET balance = balance - 50000 WHERE id = 1;
-- 대기


-- [S1] 3
COMMIT;
-- 세션 2의 대기가 풀립니다.
-- 이때 세션 2는 자기가 읽어둔 옛날 값이 아니라,
-- 방금 커밋된 최신 잔액 30000을 다시 읽어서 거기서 50000을 뺍니다.


-- [S2] 4
COMMIT;


-- [S1] 5
SELECT * FROM accounts WHERE id = 1;
-- balance = -20000
-- 12만 원이 빠졌고 잔액도 정확히 12만 원 줄었습니다. 사라진 돈이 없습니다.


-- ------------------------------------------------------------
-- 읽기와 쓰기 사이에 남이 끼어들 틈이 없어서 안 틀립니다.
-- balance = balance - 70000 의 오른쪽 balance를 DB가 직접, 그 순간에 읽습니다.
--
-- 다만 잔액이 음수가 됐습니다. "잔액 부족이면 출금 안 됨" 같은 규칙은
-- 이 한 문장만으로는 지켜지지 않습니다. 조건을 같이 걸어야 합니다.
--
--   UPDATE accounts SET balance = balance - 70000
--    WHERE id = 1 AND balance >= 70000;
--
--   -> 갱신된 행 수가 0이면 잔액이 부족한 것입니다.
--      애플리케이션에서 이걸 보고 판단하면 됩니다.
--
-- MySQL 8.0에서도 결과가 같습니다. 이 방법은 DB를 안 가립니다.
-- ------------------------------------------------------------
